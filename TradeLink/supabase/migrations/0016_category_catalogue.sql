-- ---------------------------------------------------------------------------
-- A supplier can only list a product under a category of THEIR industry. Checked when a product is added or its category changes,
-- so products saved earlier are never affected. Admin-created products (products table) are not restricted.
-- ---------------------------------------------------------------------------
create or replace function public.supplier_products_check_category()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_ind uuid; v_cat_ind uuid; v_active boolean;
begin
  if new.category_id is null then return new; end if;
  if tg_op = 'UPDATE' and new.category_id is not distinct from old.category_id then return new; end if;
  select industry_id into v_ind from public.suppliers where id = new.supplier_id;
  select industry_id, active into v_cat_ind, v_active from public.categories where id = new.category_id;
  if v_cat_ind is null or v_cat_ind is distinct from v_ind then raise exception 'Choose a category from your own industry.'; end if;
  if not v_active then raise exception 'That category is no longer available. Choose another one.'; end if;
  return new;
end;
$$;
drop trigger if exists supplier_products_check_category on public.supplier_products;
create trigger supplier_products_check_category before insert or update of category_id on public.supplier_products
  for each row execute function public.supplier_products_check_category();
revoke execute on function public.supplier_products_check_category() from public, anon, authenticated;
